#!/usr/bin/env bash
# Entrypoint of the evcrawl `dev` image (AGENTS.md §4, §9).
# Runs as root once per container start: applies team membership from
# /opt/team (baked into the image), prepares persistent SSH host keys, exposes
# the container environment to SSH sessions, then execs sshd.
set -euo pipefail

TEAM_DIR=${TEAM_DIR:-/opt/team}
HOME_ROOT=/home
UIDMAP="$HOME_ROOT/.uidmap"          # login:uid, on the homes volume, keeps uids stable
HOSTKEY_DIR=/etc/ssh/host_keys
FIRST_UID=2000

log() { printf 'team-entrypoint: %s\n' "$*" >&2; }

# --- SSH host keys (persist on the sshhost volume) --------------------------
mkdir -p "$HOSTKEY_DIR"
for t in ed25519 rsa; do
  key="$HOSTKEY_DIR/ssh_host_${t}_key"
  if [[ ! -f "$key" ]]; then
    log "generating $t host key"
    ssh-keygen -q -t "$t" -N '' -f "$key"
  fi
done
chmod 0600 "$HOSTKEY_DIR"/ssh_host_*_key
chmod 0644 "$HOSTKEY_DIR"/ssh_host_*_key.pub

# --- environment for SSH sessions -------------------------------------------
# sshd does not pass the container environment to sessions, and sshd honours
# only the first SetEnv directive. PAM's pam_env (enabled in /etc/pam.d/sshd)
# reads /etc/environment for every session: interactive shells, `ssh host cmd`,
# and editors' remote servers alike. profile.d mirrors it for login shells
# spawned from inside (tmux, su-less subshells).
# UV_CACHE_DIR is not among them: the uv cache is per user (F-008), see below.
ENV_VARS=(UV_LINK_MODE UV_PYTHON_DOWNLOADS PYTHONUNBUFFERED
          DATABASE_URL REDIS_URL NOMINATIM_URL LOG_LEVEL)
while IFS= read -r v; do ENV_VARS+=("$v"); done < <(compgen -e | grep '^EVCRAWL_' || true)
# psql/pg_dump defaults, derived from the shared db service. Members are the
# non-superuser `team` role (F-014); compose sets PGPASSWORD from the host
# .env and there is no default, so an unset one is left out, not guessed.
export PGHOST=${PGHOST:-db} PGPORT=${PGPORT:-5432} PGUSER=${PGUSER:-team} \
       PGDATABASE=${PGDATABASE:-evcrawl}
[[ "$PGUSER" != evcrawl ]] || log "warning: PGUSER is the superuser evcrawl (F-014)"
ENV_VARS+=(PGHOST PGPORT PGUSER PGDATABASE PGPASSWORD)

{
  echo '# Generated by team-entrypoint at container start (read by pam_env).'
  for var in "${ENV_VARS[@]}"; do
    [[ -n "${!var:-}" ]] && printf '%s="%s"\n' "$var" "${!var//\"/}"
  done
} > /etc/environment
{
  echo '# Generated by team-entrypoint; do not edit inside the container.'
  for var in "${ENV_VARS[@]}"; do
    [[ -n "${!var:-}" ]] && printf 'export %s=%q\n' "$var" "${!var}"
  done
  # Per-user uv cache (F-008). Sessions that skip profile.d (ssh host cmd,
  # editors' remote servers) land on the same path: it is uv's default.
  # The first login seeds it from the image's read-only pre-warmed cache.
  echo 'export UV_CACHE_DIR="$HOME/.cache/uv"'
  echo '[ -d "$UV_CACHE_DIR" ] || { mkdir -p "$HOME/.cache" && cp -r /opt/uv-cache "$UV_CACHE_DIR"; } 2>/dev/null'
} > /etc/profile.d/evcrawl.sh
chmod 0644 /etc/environment /etc/profile.d/evcrawl.sh

cat > /etc/motd <<'MOTD'

  evcrawl dev container -- shared team workspace (see AGENTS.md section 4)

  First time?   git clone <repo> ~/usher && cd ~/usher && uv sync && evcrawl --help
  Gates:        ruff check . && ruff format --check . && mypy && pytest -q
  Database:     psql            (shared dev db; PG* vars preset; --dry-run / --limit for crawls)
  Agents:       run as YOU, inside ~/usher only; no root, no sudo, no docker here (AGENTS.md section 4)
  Long jobs:    run them in tmux under your user, announce them, stop them when done.

MOTD

# --- team membership ---------------------------------------------------------
getent group team >/dev/null || groupadd --system team
touch "$UIDMAP"; chmod 0644 "$UIDMAP"

next_uid() {
  local u=$FIRST_UID
  while cut -d: -f2 "$UIDMAP" | grep -qx "$u" || getent passwd "$u" >/dev/null; do u=$((u+1)); done
  echo "$u"
}

declare -A ACTIVE=()
while read -r login _; do
  [[ -z "$login" || "$login" == \#* ]] && continue
  if ! [[ "$login" =~ ^[a-z_][a-z0-9_-]{0,31}$ ]]; then
    log "skipping invalid login '$login'"; continue
  fi
  keyfile="$TEAM_DIR/keys/$login.pub"
  if [[ ! -s "$keyfile" ]]; then
    log "skipping $login: no key at team/keys/$login.pub"; continue
  fi
  ACTIVE[$login]=1

  uid=$(awk -F: -v l="$login" '$1==l{print $2}' "$UIDMAP")
  if [[ -z "$uid" ]]; then
    uid=$(next_uid); echo "$login:$uid" >> "$UIDMAP"
  fi
  home="$HOME_ROOT/$login"
  if ! getent passwd "$login" >/dev/null; then
    if [[ -d "$home" ]]; then
      useradd --uid "$uid" --no-create-home --home-dir "$home" --shell /bin/bash --groups team "$login"
    else
      useradd --uid "$uid" --create-home --home-dir "$home" --shell /bin/bash --groups team "$login"
    fi
    passwd -l "$login" >/dev/null
    log "user $login (uid $uid) ready"
  fi
  if [[ "$(stat -c %u "$home")" != "$uid" ]]; then chown -R "$uid:$uid" "$home"; fi
  chmod 0750 "$home"   # homes are private: agents and people cannot read each other's work

  install -d -m 0700 -o "$uid" -g "$uid" "$home/.ssh"
  install -m 0600 -o "$uid" -g "$uid" "$keyfile" "$home/.ssh/authorized_keys"
done < "$TEAM_DIR/members.txt"

# Homes of people no longer in members.txt stay on disk but cannot log in.
for d in "$HOME_ROOT"/*/; do
  login=$(basename "$d")
  [[ -n "${ACTIVE[$login]:-}" ]] && continue
  if [[ -f "$d.ssh/authorized_keys" ]]; then
    rm -f "$d.ssh/authorized_keys"; log "revoked access for $login (home kept)"
  fi
done

log "members: ${!ACTIVE[@]}"
exec "$@"
